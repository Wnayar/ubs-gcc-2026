"""SHOWDOWN phase 2 — Reading the Table (docs/phases/showdown/phase-2/).

The showdown rule is hidden behind an opaque `table_rule` codename and changes every
leg. These tests pin the inference: learn the rule from the showdowns in
`recent_hands`, keep what we learn per codename, and never let an unknown table make
us bet as though it were the standard one.
"""
import json

