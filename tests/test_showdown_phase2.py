def test_a_long_lived_process_still_answers_fast():
    # the belief is recomputed whenever a new showdown arrives, and a codename
    # accumulates observations across every leg and retry — so the cost has to
    # stay flat against a store far larger than one attempt produces
    import time

    from app.showdown_rules import showdown_winners
    from app.showdown_rules import BY_NAME as _BY

    rng = __import__("random").Random(2)
    rule = _BY["near"]
    for i in range(600):
        a, b, c = rng.randint(1, 13), rng.randint(1, 13), rng.randint(1, 13)
        observe("busy", match_id=f"m{i // 40}", leg=1, hand_number=i,
                numbers={0: a, 1: b}, community=c,
                winners=showdown_winners(rule, {0: a, 1: b}, c))
    assert RuleBelief.for_codename("busy").count == 600

    start = time.perf_counter()
    for i in range(20):
        hands = [hand({0: rng.randint(1, 13), 1: rng.randint(1, 13)},
                      rng.randint(1, 13), [0], 5000 + i * 20 + j) for j in range(20)]
        r = move(table_rule="busy", recent_hands=hands)
        assert r.status_code == 200
    per_call = (time.perf_counter() - start) / 20
    assert per_call < 0.25, f"{per_call * 1000:.0f} ms per /move against a 5 s budget"
