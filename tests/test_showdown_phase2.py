def test_a_contradictory_observation_does_not_kill_a_rule_outright():
    teach("noisy", "standard", hands=30, seed=5)
    observe("noisy", match_id="x", leg=1, hand_number=99,
            numbers={0: 1, 1: 13}, community=9, winners=[0])  # impossible
    belief = posterior_for("noisy")
    assert max(belief, key=belief.get) == "standard"
    assert belief["standard"] > 0.5


# ─────────────────────────── equity follows the belief ──────────────────────────


def test_equity_under_the_standard_rule_matches_the_closed_form():
    from app.showdown import equity

    std = {"standard": 1.0}
    for n in range(1, 14):
        for c in range(1, 14):
            assert abs(rule_equity(std, n, c) - equity(n, c)) < 1e-9
        assert abs(rule_equity(std, n, None) - equity(n, None)) < 1e-9


def test_equity_inverts_when_the_rule_inverts():
    low = {"low": 1.0}
    # under "lower wins", a 1 is the monster and a 13 is the trash
    assert rule_equity(low, 1, 7) > 0.9
    assert rule_equity(low, 13, 7) < 0.1


def test_an_undecided_belief_pulls_equity_toward_a_coin_flip():
    flat = {r.name: 1 / len(RULES) for r in RULES}
    spread = [rule_equity(flat, n, 7) for n in range(1, 14)]
    assert max(spread) - min(spread) < 0.55, "unknown table must not look confident"


