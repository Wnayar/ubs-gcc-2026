from app.main import app
from app.showdown_rules import (
    KNOWN_RULES,
    RULES,
    RuleBelief,
    forget_all,
    observe,
    posterior_for,
    rule_equity,
    showdown_winners,
)

client = TestClient(app)


def setup_function():
    forget_all()  # each test starts with no memory of any codename


# ───────────────────────────── the rule representation ──────────────────────────


def test_every_rule_is_a_total_ordering_over_the_deck():
    for rule in RULES:
        for c in range(1, 14):
            keys = [rule.key(n, c) for n in range(1, 14)]
            assert len(keys) == 13
            # keys must be mutually comparable, i.e. sortable without error
            sorted(keys)


def test_the_standard_rule_reproduces_the_guides_showdown():
    std = next(r for r in RULES if r.name == "standard")
    # "any pair beats any non-pair", then "the higher number wins", else a split
    assert showdown_winners(std, {0: 7, 1: 13}, community=7) == [0]
    assert showdown_winners(std, {0: 9, 1: 11}, community=3) == [1]
    assert showdown_winners(std, {0: 6, 1: 6}, community=2) == [0, 1]
    assert showdown_winners(std, {0: 5, 1: 5}, community=5) == [0, 1]


def test_the_rule_the_statement_says_is_not_in_play_is_absent():
    # "Odd numbers beat even numbers; within each group, higher still wins." —
    # we are told it is not in play, so it gets no prior mass
    from app.showdown_rules import EXCLUDED, _signature

    excluded = _signature(EXCLUDED)
    assert all(_signature(rule) != excluded for rule in RULES)


def test_no_two_hypotheses_are_the_same_rule_in_disguise():
    # duplicates would split the posterior between identical explanations and
    # halve our confidence for no reason
    from app.showdown_rules import _signature

    seen = {}
    for rule in RULES:
        sig = _signature(rule)
        assert sig not in seen, f"{rule.name} is really {seen.get(sig)}"
        seen[sig] = rule.name


# ──────────────────────────────── learning a rule ───────────────────────────────


def hand(numbers, community, winners, hand_number=1):
    return {
        "hand_number": hand_number,
        "community_number": community,
        "winners": winners,
        "pot": 20,
        "shown_numbers": {str(k): v for k, v in numbers.items()},
        "actions": [],
    }


def teach(codename, rule_name, hands=40, seed=0):
    """Feed the store real showdowns generated by one rule."""
    import random

    rng = random.Random(seed)
    rule = next(r for r in RULES if r.name == rule_name)
    for i in range(hands):
        a, b, c = rng.randint(1, 13), rng.randint(1, 13), rng.randint(1, 13)
        observe(
            codename,
            match_id=f"m{i}",
            leg=1,
            hand_number=i + 1,
            numbers={0: a, 1: b},
            community=c,
            winners=showdown_winners(rule, {0: a, 1: b}, c),
        )
    return rule


def test_an_unseen_codename_starts_at_the_phase_one_rule():
    # deliberately NOT flat. Three of the four real phase-2 tables were best
    # explained by phase 1's rule, so an unknown table starts there and lets
    # evidence move it; a flat prior over thirty hypotheses leaves us at a coin
    # flip for the first dozen hands of a 40-hand leg.
    belief = posterior_for("chalcedony")
    assert abs(sum(belief.values()) - 1.0) < 1e-9
    assert max(belief, key=belief.get) == "standard"
    assert 0.3 < belief["standard"] < 0.6, "a prior, not a conviction"


def test_evidence_still_overrules_the_prior():
    teach("contrary", "low", hands=40, seed=8)
    belief = posterior_for("contrary")
    assert belief["standard"] < 0.01
    assert rule_equity(belief, 1, 5) > 0.8


def test_an_all_in_refund_is_not_treated_as_a_tie():
    # Two winners holding DIFFERENT numbers is not a split — when both players
    # are all in, chips nobody could cover go back and the log lists both seats.
    # Every one we have seen came from a pot of 127-405 against a median of 8
    # for decided hands. Believing them made three tables look like the deck was
    # grouped into bands, and cost us a leg.
    assert not observe("refund", match_id="m", leg=1, hand_number=1,
                       numbers={0: 12, 1: 13}, community=4, winners=[0, 1],
                       pot=405, starting_stack=200)
    assert RuleBelief.for_codename("refund").count == 0
    # a genuine tie — identical numbers — is still evidence at any pot size
    assert observe("refund", match_id="m", leg=1, hand_number=2,
                   numbers={0: 9, 1: 9}, community=4, winners=[0, 1],
                   pot=405, starting_stack=200)
    # and so is an honest tie between DIFFERENT numbers in a normal pot: under
    # "closest to the community" a 3 and a 7 both sit two away from a 5, so the
    # numbers alone must not condemn it — only an all-in-sized pot does
    assert observe("refund", match_id="m", leg=1, hand_number=3,
                   numbers={0: 3, 1: 7}, community=5, winners=[0, 1],
                   pot=8, starting_stack=200)
    assert RuleBelief.for_codename("refund").count == 2


def test_a_lucky_number_rule_is_learnable():
    # amaranth: a 7 beat an 8 twice at different community numbers, and never lost
    teach("lucky", "lucky7", hands=60, seed=2)
    belief = posterior_for("lucky")
    truth = {"lucky7": 1.0}
    worst = max(abs(rule_equity(belief, n, c) - rule_equity(truth, n, c))
                for n in range(1, 14) for c in range(1, 14))
    assert worst < 0.10, belief


